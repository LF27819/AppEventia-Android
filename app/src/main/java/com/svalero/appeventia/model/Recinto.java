package com.svalero.appeventia.model;

public class Recinto {

    private long id;
    private String nombre;
    private String direccion;
    private String ciudad;

    public Recinto() {
    }

    public long getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public String getDireccion() {
        return direccion;
    }

    public String getCiudad() {
        return ciudad;
    }
}